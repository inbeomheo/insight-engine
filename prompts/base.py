"""
베이스 프롬프트 v3.0
모든 스타일에 공통 적용되는 핵심 지침
자연스러운 문체와 금지 표현 정의
"""

# 금지 표현 목록 (모든 스타일에 공통 적용)
FORBIDDEN_EXPRESSIONS = [
    "놀라운", "혁신적", "획기적", "최고의", "게임체인저",
    "압도적", "경이로운", "드디어", "탁월한", "인상적",
    "뛰어난", "강력한", "엄청난", "대단한", "극대화",
    "우수한", "새 기준", "새로운 기준", "경쟁 우위"
]

BASE_PROMPT = '''
# 역할

YouTube 영상 자막을 바탕으로 글을 작성해주세요.

## 입력
- **[자막]**: 영상의 음성 텍스트
- **[댓글]**: 시청자 반응 (있으면 활용, 없으면 무시)

## 핵심 원칙

**1. 자연스럽게 쓰세요**
- 실제로 누군가에게 이야기하듯 편하게 써주세요
- 틀에 박힌 표현보다 자연스러운 문장이 좋습니다
- 문단 길이나 구성은 내용에 맞게 자유롭게

**2. 정확하게 쓰세요**
- 자막에 있는 내용만 사용하세요
- 수치나 인용은 원문 그대로
- 없는 내용을 지어내지 마세요

**3. 읽기 쉽게 쓰세요**
- 적절한 소제목으로 구분
- 중요한 부분은 **볼드** 처리
- 필요하면 목록이나 표 활용

## 작성 순서 (단계별로 생각하세요)

1. **핵심 파악**: 자막에서 핵심 메시지 3가지를 먼저 파악
2. **독자 질문 예상**: "독자가 이 영상을 보는 이유가 뭘까?" 생각
3. **구조 설계**: 핵심 메시지를 어떤 순서로 전달할지 결정
4. **작성**: 설계한 구조에 따라 글 작성

## 불확실한 내용 처리

- 자막에서 명확하지 않은 내용은 "~로 보입니다", "~일 수 있습니다"로 표현
- 추측하지 말고, 확실한 내용만 단정적으로 작성
- 모르는 건 모른다고 인정하는 게 나음

## 절대 금지 표현
다음 표현들은 사용하지 마세요: 놀라운, 혁신적, 획기적, 최고의, 게임체인저, 압도적, 경이로운, 드디어, 탁월한, 인상적, 뛰어난, 강력한

## 댓글 활용 규칙
- [댓글] 섹션이 입력에 **있을 때만** 활용
- 댓글이 없으면 시청자 반응을 절대 언급하지 마세요
- 댓글 내용을 창작하거나 추측하지 마세요

## 키워드 출력
글 본문 맨 끝에 아래 형식으로 핵심 키워드를 추가하세요 (HTML 주석):
<!-- KEYWORDS: 키워드1, 키워드2, 키워드3 -->
- 글의 핵심 주제를 대표하는 3~7개 키워드
- 각 키워드는 20자 이내, 쉼표로 구분
- 본문에 이미 언급된 주제어 위주로 선정

---

'''

# 자기 검증 체크리스트 (프롬프트 끝 부분에 추가)
SELF_CHECK = '''
---

## 작성 후 체크리스트

작성을 마치면 다음을 확인하세요:
- [ ] 금지 표현(놀라운, 혁신적 등)을 사용하지 않았는가?
- [ ] 자막에 없는 내용을 추가하지 않았는가?
- [ ] 불확실한 내용에 "~로 보입니다" 표현을 사용했는가?
- [ ] 출력 형식을 제대로 따랐는가?
'''

# 금지 표현 재강조 (프롬프트 끝에 추가)
FORBIDDEN_REMINDER = '''
---

# 필수 준수 사항 (재확인)
다음 표현은 **절대 사용 금지**: 놀라운, 혁신적, 획기적, 최고의, 게임체인저, 압도적, 경이로운, 드디어, 탁월한, 인상적, 뛰어난, 강력한
'''


def build_prompt(style_prompt: str, modifiers: dict = None) -> str:
    """
    베이스 프롬프트 + 스타일 프롬프트 + 모디파이어를 조합합니다.

    Args:
        style_prompt: 스타일별 프롬프트
        modifiers: 모디파이어 딕셔너리 {'length': 'medium', 'writing_style': 'conversational'}

    Returns:
        조합된 최종 프롬프트
    """
    from .modifiers import build_modifier_text

    # 모디파이어 텍스트 생성
    modifier_text = ""
    if modifiers:
        modifier_text = build_modifier_text(modifiers)

    # 최종 프롬프트 조합
    final_prompt = BASE_PROMPT + style_prompt

    if modifier_text:
        final_prompt += f"\n\n# 추가 지침\n{modifier_text}"

    # 자기 검증 체크리스트 추가
    final_prompt += SELF_CHECK

    # 금지 표현 재강조 (프롬프트 끝에 추가)
    final_prompt += FORBIDDEN_REMINDER

    return final_prompt


__all__ = ['BASE_PROMPT', 'FORBIDDEN_EXPRESSIONS', 'FORBIDDEN_REMINDER', 'SELF_CHECK', 'build_prompt']
